"""Replays packages/pca/conformance/attestation-evidence-vectors.json (vendor hardware-attestation evidence: AMD SEV-SNP,
Intel TDX DCAP, Azure MAA, GCP Confidential Space, NVIDIA GPU SPDM, plus the strict X.509 readers they share) through the
native verifiers in atlas_pca.attest. Every row's `expect` was produced by RUNNING the TypeScript verifier, so a row passes only
when the WHOLE result equals it (reason string byte for byte, except rows whose reason embeds an OpenSSL message: those compare
the stable prefix). The file must exist: a missing file FAILS (it is generated and committed by the reference's CI)."""
import json
import os
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
NAME = "attestation-evidence-vectors.json"


def locate(name):
    """The shared corpus: $PCA_CONFORMANCE_DIR, the monorepo layout, a flagship checkout beside the tests, or conformance/."""
    cands = [
        os.environ.get("PCA_CONFORMANCE_DIR") or "",
        os.path.join(HERE, "conformance"),
        os.path.join(HERE, "packages", "pca", "conformance"),
        os.path.join(HERE, "conformance"),
    ]
    for d in cands:
        if d and os.path.isfile(os.path.join(d, name)):
            return os.path.join(d, name)
    return None


def have_cryptography():
    try:
        import cryptography  # noqa: F401
    except ImportError:
        return False
    return True


# PCA_REQUIRE_ATTEST=1 (set in CI) turns a missing `cryptography` into a failure instead of a skip
REQUIRE = os.environ.get("PCA_REQUIRE_ATTEST") == "1"
NEEDS_CRYPTO = unittest.skipUnless(have_cryptography() or REQUIRE, "needs the `cryptography` package (extra `attest`)")


def hydrate(x, blobs):
    """Replace every {"$blob": id} with blobs[id]."""
    if isinstance(x, list):
        return [hydrate(e, blobs) for e in x]
    if isinstance(x, dict):
        if list(x.keys()) == ["$blob"]:
            return blobs[x["$blob"]]
        return {k: hydrate(v, blobs) for k, v in x.items()}
    return x


def load():
    path = locate(NAME)
    if path is None:
        raise AssertionError(
            "conformance/%s is missing: it is generated by the reference (`tsx scripts/gen-conformance-attestation.ts`) and committed; "
            "this suite must not skip without it" % NAME
        )
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def same(got, want):
    """The whole result equals the expectation (prefix rows compare the stable reason prefix and everything else exactly)."""
    want = dict(want)
    if want.pop("reason_match", None) == "prefix":
        prefix = want.pop("reason_prefix")
        reason = got.get("reason")
        g = {k: v for k, v in got.items() if k != "reason"}
        w = {k: v for k, v in want.items() if k != "reason"}
        return isinstance(reason, str) and reason.startswith(prefix) and g == w
    return got == want


@NEEDS_CRYPTO
class AttestationVectors(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.doc = load()

    def test_documents_every_vendor(self):
        from atlas_pca.attest import VENDORS

        self.assertEqual(sorted(self.doc["verifier_config_schema"].keys()), sorted(VENDORS))

    def test_coverage_and_intents(self):
        rows = self.doc["attestation_vectors"]
        self.assertEqual(len(set(r["id"] for r in rows)), len(rows))
        for vendor, minimum in (("amd-sev-snp", 200), ("intel-tdx-dcap", 250), ("azure-maa", 150), ("gcp-confidential-space", 88), ("nvidia-gpu-spdm", 70)):
            of = [r for r in rows if r["vendor"] == vendor]
            self.assertGreaterEqual(len(of), minimum, vendor)
            self.assertTrue(any(r["intent"] == "accept" for r in of), vendor)
            self.assertTrue(any(r["intent"] == "reject" for r in of), vendor)
        self.assertGreaterEqual(len(self.doc["x509_vectors"]), 90)
        for r in rows:
            accepted = r["expect"].get("ok") is True
            self.assertEqual((r["id"], accepted), (r["id"], r["intent"] == "accept"))

    def test_every_attestation_row_answers_exactly_the_recorded_result(self):
        from atlas_pca.attest import run_attestation_vector

        bad = []
        for r in self.doc["attestation_vectors"]:
            h = hydrate(r, self.doc["blobs"])
            got = run_attestation_vector(h)
            if not same(got, h["expect"]):
                bad.append("%s: got %r want %r" % (r["id"], got, h["expect"]))
        self.assertEqual(bad[:25], [])
        self.assertEqual(len(bad), 0)

    def test_every_x509_row_answers_exactly_the_recorded_result(self):
        from atlas_pca.attest import run_x509_vector

        bad = []
        for r in self.doc["x509_vectors"]:
            got = run_x509_vector(r["fn"], r["input"])
            if got != r["expect"]:
                bad.append("%s: got %r want %r" % (r["id"], got, r["expect"]))
        self.assertEqual(bad[:25], [])
        self.assertEqual(len(bad), 0)


if __name__ == "__main__":
    unittest.main()
